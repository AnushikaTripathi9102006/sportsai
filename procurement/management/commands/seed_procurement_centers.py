class Command(BaseCommand):
    help = "Safely seeds synthetic demo Procurement Centre dataset across India into KisanFlow database."

    def add_arguments(self, parser):
        parser.add_argument(
            "--clear-synthetic",
            action="store_true",
            help="Optional: Delete previously seeded synthetic centres (codes starting with UP-, PB-, HR-, etc.) before seeding.",
        )

    def handle(self, *args, **options):
        self.stdout.write(self.style.MIGRATE_HEADING("=========================================="))
        self.stdout.write(self.style.MIGRATE_HEADING("KISANFLOW — SYNTHETIC CENTRE SEEDING"))
        self.stdout.write(self.style.MIGRATE_HEADING("=========================================="))

        clear_synthetic = options.get("clear_synthetic", False)
        if clear_synthetic:
            self.stdout.write(self.style.WARNING("Clearing previously seeded synthetic procurement centres..."))
            deleted_count, _ = ProcurementCenter.objects.filter(code__regex=r"^[A-Z]{2}-[A-Z0-9]+-\d+").delete()
            self.stdout.write(self.style.SUCCESS(f"Removed {deleted_count} old synthetic records."))

        created_count = 0
        updated_count = 0
        skipped_count = 0

        total_records = len(SYNTHETIC_CENTERS_DATA)

        for item in SYNTHETIC_CENTERS_DATA:
            code = item["code"]
            defaults_dict = {
                "name": item["name"],
                "district": item["district"],
                "tehsil_block": item["tehsil_block"],
                "address": item["address"],
                "contact_number": item["contact_number"],
                "operating_hours": item["operating_hours"],
                "crops_handled": item["crops_handled"],
                "queue_status": item["queue_status"],
                "distance_km": item["distance_km"],
                "capacity_quintals": item["capacity_quintals"],
                "is_active": item["is_active"],
            }

            center_obj, created = ProcurementCenter.objects.get_or_create(
                code=code,
                defaults=defaults_dict,
            )

            if created:
                created_count += 1
            else:
                # Update existing fields to ensure demo data consistency without deleting DB record
                updated = False
                for field, val in defaults_dict.items():
                    if getattr(center_obj, field) != val:
                        setattr(center_obj, field, val)
                        updated = True
                if updated:
                    center_obj.save()
                    updated_count += 1
                else:
                    skipped_count += 1

        self.stdout.write("")
        self.stdout.write(self.style.SUCCESS(f"✅ Seeding Complete!"))
        self.stdout.write(f"   • Total Seed Records Processed: {total_records}")
        self.stdout.write(f"   • Newly Created Centres: {created_count}")
        self.stdout.write(f"   • Updated Existing Centres: {updated_count}")
        self.stdout.write(f"   • Unchanged Records (Skipped): {skipped_count}")
        self.stdout.write(f"   • Total Procurement Centers in Database: {ProcurementCenter.objects.count()}")

        active_count = ProcurementCenter.objects.filter(is_active=True).count()
        inactive_count = ProcurementCenter.objects.filter(is_active=False).count()
        up_count = ProcurementCenter.objects.filter(district__in=[
            "Lucknow", "Barabanki", "Kanpur Nagar", "Kanpur Dehat", "Unnao", "Sitapur", "Hardoi",
            "Lakhimpur Kheri", "Raebareli", "Prayagraj", "Varanasi", "Ayodhya", "Agra", "Meerut",
            "Bareilly", "Gorakhpur", "Jhansi", "Mathura", "Aligarh", "Moradabad", "Saharanpur",
            "Farrukhabad", "Etawah", "Mainpuri", "Firozabad", "Shahjahanpur", "Basti", "Gonda",
            "Bahraich", "Sultanpur", "Amethi", "Bijnor", "Muzaffarnagar", "Rampur", "Sambhal",
            "Bulandshahr", "Banda", "Jalaun"
        ]).count()

        self.stdout.write("")
        self.stdout.write(self.style.MIGRATE_LABEL("DATASET SUMMARY:"))
        self.stdout.write(f"   - Uttar Pradesh Centres: {up_count}")
        self.stdout.write(f"   - Active Centres: {active_count} ({round(active_count/max(1, ProcurementCenter.objects.count())*100, 1)}%)")
        self.stdout.write(f"   - Inactive Centres: {inactive_count}")
        self.stdout.write(self.style.MIGRATE_HEADING("=========================================="))
